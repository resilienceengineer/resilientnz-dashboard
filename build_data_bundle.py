"""
Bundle every snapshot in ./data into data_bundle.js so the app can run
straight from file:// (double-click index.html) with no local server —
<script> tags load from disk where fetch() cannot.

Run after refreshing any snapshot:  python build_data_bundle.py
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
DATA = HERE / "data"
OUT = HERE / "data_bundle.js"


def main():
    parts = ["// Generated by build_data_bundle.py — do not edit by hand.",
             "const LOCAL_DATA = {};"]
    total = 0
    for f in sorted(DATA.glob("*.geojson")):
        key = f.stem
        text = f.read_text(encoding="utf-8")
        json.loads(text)               # sanity check
        parts.append(f'LOCAL_DATA[{json.dumps(key)}] = {text};')
        total += len(text)
        print(f"  bundled {key}  ({len(text) // 1024:,} KB)")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"Wrote {OUT.name}  ({total // 1024 // 1024} MB total)")


if __name__ == "__main__":
    main()
